package com.lxisoft.car;

public class Car
{
private String name;
private String doorDetails;
private String tyreDetails;
private String steeringDetails;

public String getSteeringDetails() {
    return steeringDetails;
}
public void setSteeringDetails(String steeringDetails) {
    this.steeringDetails = steeringDetails;
}
public String getName() {
    return name;
}
public void setName(String name) {
    this.name = name;
}
public String getDoorDetails() {
    return doorDetails;
}
public void setDoorDetails(String doorDetails) {
    this.doorDetails = doorDetails;
}
public String getTyreDetails() {
    return tyreDetails;
}
public void setTyreDetails(String tyreDetails) {
    this.tyreDetails = tyreDetails;
}
    
}